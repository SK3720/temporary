#!/usr/bin/env python3
"""Convert a .tflite file into firmware/asl_sign/model_data.cpp.

The generated file carries the label list alongside the model bytes, so the
firmware always uses the labels that match the model it was built with.

  python tools/tflite_to_c.py model.tflite --labels ABCDEFGHIJKLMNOPQRSTUVWXYZ
  python tools/tflite_to_c.py stock.tflite --labels ABCDEFGHIKLMNOPQRSTUVWXY   # stock 24-class
"""
import argparse
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "firmware" / "asl_sign" / "model_data.cpp"


def write_c(data, labels, out=DEFAULT_OUT, note="", source="model.tflite"):
    """Write model bytes + label list as model_data.cpp."""
    if data[4:8] != b"TFL3":
        raise SystemExit("not a .tflite flatbuffer: " + source)
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    label_list = ", ".join(f'"{c}"' for c in labels)

    src = f"""// GENERATED by tools/tflite_to_c.py - do not edit by hand.
// source: {source}  ({len(data)} bytes)
// {note}
#include "model_data.h"

alignas(16) const unsigned char g_model[] = {{
{chr(10).join(lines)}
}};
const unsigned int g_model_len = {len(data)};

const char* const kLabels[] = {{{label_list}}};
const int kNumLabels = {len(labels)};
"""
    pathlib.Path(out).write_text(src)
    print(f"wrote {out}: {len(data)} bytes, {len(labels)} labels ({labels})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tflite")
    ap.add_argument("--labels", required=True,
                    help="one character per output class, in output order")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--note", default="", help="comment line stored in the file")
    a = ap.parse_args()
    write_c(pathlib.Path(a.tflite).read_bytes(), a.labels, a.out, a.note, pathlib.Path(a.tflite).name)


if __name__ == "__main__":
    main()
