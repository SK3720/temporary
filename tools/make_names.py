#!/usr/bin/env python3
"""Build firmware/asl_sign/names.h: ~1000 common first names, most common first.

Source: US Social Security baby-name shares (hadley/data-baby-names on GitHub),
summed over 1950-2008, plus a hand-added list of common international names.

  curl -L -o baby-names.csv https://raw.githubusercontent.com/hadley/data-baby-names/master/baby-names.csv
  python tools/make_names.py baby-names.csv
"""
import collections
import csv
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "firmware" / "asl_sign" / "names.h"
N_US = 900

# Common names the US list under-represents (judges may be from anywhere).
EXTRA = """
AHMED ALI OMAR FATIMA AISHA MOHAMMED MUHAMMAD YUSUF HASSAN HUSSEIN IBRAHIM
ZAINAB MARIAM LAYLA NOOR AMIR KARIM RANIA SARA HAMZA ZOE ZARA
PRIYA RAHUL ANIL SUNIL AMIT ROHAN ARJUN RAVI NEHA POOJA ANJALI DEEPAK VIJAY
KAVYA ISHA AARAV VIVEK ADITYA SANJAY MEERA ASHA RAJ KIRAN ARUN NIKHIL
WEI LI MING JUN YAN HUI LING CHEN XIN HAO YU JIE LEI TAO FANG
KENJI YUKI HIRO SORA MIN JI HYUN SEO
CHIDI EMEKA KOFI KWAME AMARA ADAEZE TUNDE FEMI NGOZI
JOSE JUAN LUIS CARLOS DIEGO JAVIER MIGUEL PABLO SOFIA LUCIA DIANA ELENA
MATEO SANTIAGO CAMILA VALENTINA ISABELA GABRIEL RAFAEL
LUCA MARCO GIULIA CHIARA FRANCESCO LUKAS FELIX JONAS LENA LEA HANNAH
IVAN OLGA IRINA DMITRI SERGEI ANYA NADIA SASHA MAXIM
AVA MIA EMMA NOAH LIAM ETHAN OLIVIA AMELIA ISLA CHLOE
MATT TOM BEN SAM ALEX MAX DAN JOE TIM NICK MIKE JAKE JOSH CHRIS ROB BOB BILL WILL JEN KATE KATIE LIZ SAM JESS BETH ABBY TONY STEVE DAVE JIM PAT
""".split()


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "baby-names.csv"
    score = collections.Counter()
    with open(src, newline="") as f:
        for row in csv.DictReader(f):
            if 1950 <= int(row["year"]) <= 2008:
                score[row["name"].upper()] += float(row["percent"])
    us = [n for n, _ in score.most_common() if n.isalpha() and n.isascii()][:N_US]
    names, seen = [], set()
    for n in us + EXTRA:
        if n not in seen and len(n) <= 12:
            seen.add(n)
            names.append(n)

    body = []
    for i in range(0, len(names), 10):
        body.append("  " + ", ".join(f'"{n}"' for n in names[i:i + 10]) + ",")
    OUT.write_text(f"""// GENERATED by tools/make_names.py - most common first.
#pragma once
static const char* const kNames[] = {{
{chr(10).join(body)}
}};
static const int kNumNames = {len(names)};
""")
    print(f"wrote {OUT}: {len(names)} names")


if __name__ == "__main__":
    main()
